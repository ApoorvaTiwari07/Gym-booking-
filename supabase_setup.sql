-- 1. Create the 'users' table to store new users who register or sign in
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL,
  phone TEXT,
  goal TEXT DEFAULT 'General Fitness',
  role TEXT DEFAULT 'member',
  password TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  last_login TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;

-- 3. Simple policies so public web users can read and insert their account data
CREATE POLICY "Allow select on users"
ON public.users
FOR SELECT
TO anon, authenticated
USING (true);

CREATE POLICY "Allow insert on users"
ON public.users
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

CREATE POLICY "Allow update on users"
ON public.users
FOR UPDATE
TO anon, authenticated
USING (true);

